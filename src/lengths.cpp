static std::string at(std::uint64_t p, std::uint64_t length) {
	return "exponent " + std::to_string(p) + " at length " + std::to_string(length);
}


bool ibdwt::is_supported(std::uint64_t length) {
	return length <= LARGEST_LENGTH and fft::is_supported(length);
}


std::vector<std::uint64_t> ibdwt::supported_lengths() {
	//
	// The lengths m 2^k up to LARGEST_LENGTH, odd m up to 15, ascending: each length has one odd
	// factor, so none comes twice

	std::vector<std::uint64_t> lengths;
	for (std::uint64_t m = 1; m <= fft::LARGEST_ODD_FACTOR; m += 2)
		for (std::uint64_t n = m; n <= LARGEST_LENGTH; n *= 2)
			lengths.push_back(n);
	std::sort(lengths.begin(), lengths.end());
	return lengths;
}


std::uint64_t ibdwt::largest_exponent(std::uint64_t length) {
	auto entry = largest_exponent_by_length.find(length);
	if (not is_supported(length))
		throw engine_error("length " + std::to_string(length) + " is not supported, so it holds no exponent");
	if (entry == largest_exponent_by_length.end())
		throw engine_error("length " + std::to_string(length) + " has no row in the length table");
	return entry->second;
}


bool ibdwt::holds(std::uint64_t length, std::uint64_t p) {
	if (not is_supported(length) or largest_exponent_by_length.count(length) == 0)
		return false;
	return p >= 3 and p >= length and p <= largest_exponent_by_length.at(length);
}


void ibdwt::require_held(std::uint64_t length, std::uint64_t p) {
	//
	// Refuse, naming the exponent and the length, unless the table lets the length hold p

	if (not is_supported(length))
		throw engine_error(at(p, length) + ": the length is not supported (m 2^k up to 2^20 words, odd m up to 15)");
	if (not holds(length, p))
		throw engine_error(at(p, length) + ": the length table does not let this length hold the exponent");
}


std::uint64_t ibdwt::length_for(std::uint64_t p) {
	for (std::uint64_t n: supported_lengths())
		if (holds(n, p))
			return n;
	throw engine_error("exponent " + std::to_string(p) + ": no supported length holds it");
}


double ibdwt::rms_envelope(std::uint64_t length) {
	auto entry = rms_envelope_by_length.find(length);
	if (not is_supported(length))
		throw engine_error("length " + std::to_string(length) + " is not supported, so it has no envelope");
	if (entry == rms_envelope_by_length.end())
		throw engine_error("length " + std::to_string(length) + " has no row in the length table");
	return entry->second;
}
